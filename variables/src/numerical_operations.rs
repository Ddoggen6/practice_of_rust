fn main() {
    //addition
    let sum: i32 = 5 + 10;

    //susbtraction
    let difference: i32 = 5 - 10;

    //multiplication
    let product: i32 = 5 * 10;

    //division
    let quotient: f64 = 56.7 / 32.2;
    let truncated: i32 = -5 / 3;

    //module
    let reminder = 43 % 5;

    println!("Result of the sum: {sum}");
    println!("Result of the difference: {difference}");
    println!("Result of the product: {product}");
    println!("Result of the quotient: {quotient}");
    println!("Result of the truncated: {truncated}");
    println!("Result of the module: {reminder}");
}
