fn main() {
    //intergers
    let mut interger_x: i32 = 5;
    println!("The value of x is: {interger_x}");
    interger_x = 6;
    println!("The value of x is: {interger_x}");

    //floats
    let float_x = 2.2; //f64, double precision

    let float_y: f32 = 3.2; //f32 has single precision
    println!("The value of float_x is: {float_x}");
    println!("The value of float_x is: {float_y}");
}
